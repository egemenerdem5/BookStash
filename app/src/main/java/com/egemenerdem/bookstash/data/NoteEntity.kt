package com.egemenerdem.bookstash.data

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.PrimaryKey

@Entity(
    tableName = "notes",
    foreignKeys = [
        ForeignKey(
            entity = BookEntity::class,
            parentColumns = ["id"],
            childColumns = ["bookId"],
            onDelete = ForeignKey.CASCADE // Security measure: auto-deletes notes if parent book is deleted
        )
    ]
)
data class NoteEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0, // Auto-generated by Room
    val bookId: String, // The foreign key linking back to the BookEntity
    val contentText: String,
    val imagePath: String? = null, // Path to local app-private storage, NEVER raw bytes
    val createdAt: Long = System.currentTimeMillis()
)

